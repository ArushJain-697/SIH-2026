#!/usr/bin/env node
/**
 * Seam-Linter — invariant coverage map. Build-map ticket #13 (CORE, Phase 3).
 * Bible §4: "the repo's own scripts/enforce-*.mjs and check-*.mjs are a
 * pre-built map of the developers' threat model. Run them, read them, and
 * use any that are disabled or bypassable as a finding lead."
 *
 * WHAT THIS DOES: reads every real scripts/enforce-*.mjs / scripts/check-*.mjs
 * in the target's live source and extracts (a) its stated purpose from its
 * own header comment and (b) the concrete file/directory paths it reads —
 * i.e. exactly what surface each control actually watches. This is "audit
 * the auditor": the security gap in an AI-assisted, CI-guarded codebase
 * lives in what these scripts do NOT watch, and you cannot know that
 * without first knowing precisely what they DO watch.
 *
 * OUTPUT: framework/seam-linter/output/invariant-coverage-map.json (+ .md)
 * — real data read from the pinned commit, not a description of the class
 * of tool WorldMonitor happens to use.
 *
 * Usage: node framework/seam-linter/analyze-invariants.mjs [srcDir]
 */
import { readFileSync, readdirSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('../../', import.meta.url).pathname;
const SRC = process.argv[2] || join(ROOT, '.cache/worldmonitor-src');
const SCRIPTS_DIR = join(SRC, 'scripts');
const OUT_DIR = join(ROOT, 'framework/seam-linter/output');

if (!existsSync(SRC)) {
  console.error(`ERROR: target source not found at ${SRC} — run: bash lab/fetch-target-source.sh`);
  process.exit(2);
}

function gitCommit(dir) {
  try {
    const head = readFileSync(join(dir, '.git/HEAD'), 'utf8').trim();
    if (head.startsWith('ref:')) {
      const ref = head.slice(5).trim();
      return readFileSync(join(dir, '.git', ref), 'utf8').trim();
    }
    return head;
  } catch {
    return 'unknown';
  }
}

/** Extract the leading /** ... *\/ JSDoc-style block comment, if any. */
function extractHeaderComment(source) {
  const m = source.match(/^#!.*\n([\s\S]*?)\/\*\*([\s\S]*?)\*\//);
  const block = m ? m[2] : (source.match(/^\/\*\*([\s\S]*?)\*\//) || [, ''])[1];
  return block
    .split('\n')
    .map((l) => l.replace(/^\s*\*\s?/, '').trimEnd())
    .filter((l, i, arr) => !(l === '' && (i === 0 || i === arr.length - 1)))
    .join('\n')
    .trim();
}

/** Best-effort extraction of concrete paths the script reads: readFileSync/
 *  readdirSync string-literal args, and join(ROOT, '...') calls. This is
 *  intentionally a heuristic (these are arbitrary Node scripts, not a fixed
 *  grammar) — good enough to map coverage, not a full AST engine. */
function extractReferencedPaths(source) {
  const paths = new Set();
  const patterns = [
    /readFileSync\(\s*join\(ROOT,\s*['"]([^'"]+)['"]\)/g,
    /readdirSync\(\s*join\(ROOT,\s*['"]([^'"]+)['"]\)/g,
    /readFileSync\(\s*['"]([^'"]+\.[a-zA-Z]+)['"]/g,
    /join\(ROOT,\s*['"]([^'"]+)['"]\)/g,
    /['"](\.\/[a-zA-Z0-9_\-./]+)['"]/g,
  ];
  for (const re of patterns) {
    let m;
    while ((m = re.exec(source))) paths.add(m[1]);
  }
  return [...paths].sort();
}

function main() {
  if (!existsSync(SCRIPTS_DIR)) {
    console.error(`ERROR: ${SCRIPTS_DIR} not found`);
    process.exit(2);
  }

  const files = readdirSync(SCRIPTS_DIR).filter(
    (f) => (f.startsWith('enforce-') || f.startsWith('check-')) && f.endsWith('.mjs'),
  ).sort();

  const invariants = files.map((file) => {
    const full = join(SCRIPTS_DIR, file);
    const source = readFileSync(full, 'utf8');
    return {
      file: `scripts/${file}`,
      kind: file.startsWith('enforce-') ? 'enforce' : 'check',
      line_count: source.split('\n').length,
      purpose: extractHeaderComment(source) || '(no header comment found)',
      referenced_paths: extractReferencedPaths(source),
    };
  });

  mkdirSync(OUT_DIR, { recursive: true });
  const result = {
    tool: 'analyze-invariants',
    target_commit: gitCommit(SRC),
    checked_at: new Date().toISOString(),
    invariant_count: invariants.length,
    invariants,
  };

  writeFileSync(join(OUT_DIR, 'invariant-coverage-map.json'), JSON.stringify(result, null, 2));

  const md = [
    '# Invariant coverage map (auto-generated — do not hand-edit)',
    '',
    `Generated by \`framework/seam-linter/analyze-invariants.mjs\` against target commit \`${result.target_commit}\`, ${result.checked_at}.`,
    '',
    `${invariants.length} real \`enforce-*.mjs\`/\`check-*.mjs\` CI invariants found in the target's \`scripts/\` directory.`,
    '',
    '| # | File | Kind | Lines | Purpose (from its own header) |',
    '| --- | --- | --- | --- | --- |',
    ...invariants.map((inv, i) => `| ${i + 1} | \`${inv.file}\` | ${inv.kind} | ${inv.line_count} | ${inv.purpose.split('\n')[0].slice(0, 100)}${inv.purpose.split('\n')[0].length > 100 ? '…' : ''} |`),
    '',
    '## Full purpose text + referenced paths per invariant',
    '',
    ...invariants.flatMap((inv) => [
      `### \`${inv.file}\``,
      '',
      '```',
      inv.purpose || '(no header comment)',
      '```',
      '',
      inv.referenced_paths.length
        ? `Referenced paths: ${inv.referenced_paths.map((p) => `\`${p}\``).join(', ')}`
        : '_No concrete paths extracted by the heuristic — read the file directly._',
      '',
    ]),
  ].join('\n');

  writeFileSync(join(OUT_DIR, 'invariant-coverage-map.md'), md);

  console.log(`analyze-invariants: ${invariants.length} invariants mapped, output written to framework/seam-linter/output/`);
  console.log(JSON.stringify({ target_commit: result.target_commit, invariant_count: invariants.length }, null, 2));
}

main();
