#!/usr/bin/env node
/**
 * Generates docs/proof-spine.md from register/advisories.json — build-map
 * ticket #23 (EVIDENCE, Phase 3). Bible §5: every finding class ties to an
 * external authority AND a real advisory. This is REGENERABLE, not
 * hand-maintained prose, so it can never silently drift from the register
 * that findings/ are validated against.
 *
 * Usage: node framework/generate-proof-spine.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('../', import.meta.url).pathname;
const register = JSON.parse(readFileSync(join(ROOT, 'register/advisories.json'), 'utf8'));

const PLATFORM_ANCHORS = {
  'Vercel Edge': {
    anchor: 'vercel-labs/guarded-fetch (Vercel\'s own library implementing connect-time IP pinning to close exactly this class)',
    url: 'https://github.com/vercel-labs/guarded-fetch',
  },
  Convex: {
    anchor: 'Convex\'s own documentation: "use some form of access control for all public functions" (docs.convex.dev/understanding/best-practices)',
    url: 'https://docs.convex.dev/understanding/best-practices/',
  },
  MCP: {
    anchor: 'NSA MCP Security Design Considerations PDF; OWASP MCP Top 10 (2025) MCP03 Tool Poisoning; CVE-2025-49596 (MCP Inspector RCE); Equixly: 43% of tested MCP servers had command injection',
    url: 'https://www.nsa.gov/Portals/75/documents/Cybersecurity/CSI_MCP_SECURITY.pdf',
  },
  'MCP / Upstash': {
    anchor: 'Same MCP anchors as above, plus the reserve-then-refund TOCTOU pattern this project independently reproduced (see findings/WM-002)',
    url: 'https://www.nsa.gov/Portals/75/documents/Cybersecurity/CSI_MCP_SECURITY.pdf',
  },
  'Cloudflare edge': {
    anchor: 'Cloudflare\'s own header-trust documentation on cf-connecting-ip vs client-supplied X-Forwarded-For',
    url: 'https://developers.cloudflare.com/fundamentals/reference/http-request-headers/',
  },
  'Upstash Redis': {
    anchor: 'Atomic reservation pattern (Redis Lua) — the general fix class for TOCTOU quota bugs; see the Denial-of-Wallet research in docs/GEMINI-RESEARCH-BRIEFS.md',
    url: null,
  },
  'Sebuf / protobuf': {
    anchor: 'Proto-first RPC contract validation drift — the class this project independently re-derived for rate-limit coverage in findings/WM-003',
    url: null,
  },
  'Tauri 2': {
    anchor: 'Tauri\'s own capability/allowlist security model',
    url: 'https://tauri.app/v2/security/',
  },
  'OAuth': {
    anchor: 'RFC 9068 (JWT audience validation) / OAuth 2.1 token lifecycle guidance',
    url: 'https://www.rfc-editor.org/rfc/rfc9068.html',
  },
};

function main() {
  const rows = register.advisories.map((a) => {
    const platformInfo = PLATFORM_ANCHORS[a.platform] || { anchor: '(no external anchor catalogued yet)', url: null };
    return { ...a, external_anchor: platformInfo.anchor, external_anchor_url: platformInfo.url };
  });

  const demoRows = rows.filter((r) => r.demo_candidate);
  const otherRows = rows.filter((r) => !r.demo_candidate);

  const md = [
    '# Proof spine — platform ↔ external authority ↔ real advisory',
    '',
    '> **Auto-generated by `framework/generate-proof-spine.mjs` from `register/advisories.json`. Do not hand-edit — regenerate instead: `node framework/generate-proof-spine.mjs`.**',
    '',
    `Generated: ${new Date().toISOString()} · Register verified: ${register.verified_on} · ${register.count_published} published + ${register.count_draft} draft advisor${register.count_draft === 1 ? 'y' : 'ies'}`,
    '',
    'Every risk class this project discusses ties to (a) an external authority WorldMonitor did not write, and (b) a real advisory the maintainer already published on this exact repository. Bible §5. The single best line this produces: cite the **NSA\'s own MCP security paper** to an **NTRO** jury (India\'s NSA-equivalent), then show the target\'s own MCP advisories sitting exactly where that paper predicts.',
    '',
    '## Demo-priority rows (reproduced or independently verified in this project)',
    '',
    '| Advisory | Severity | Platform | External anchor | Our artifact |',
    '| --- | --- | --- | --- | --- |',
    ...demoRows.map((r) => {
      const findingRef = r.id === 'GHSA-r649-4cqj-w93h' ? 'findings/WM-001'
        : r.id === 'GHSA-hcq5-jm84-2395' ? 'findings/WM-002'
        : r.id === 'GHSA-c267-988w-7pq7' ? '(not yet reproduced — future work)'
        : '—';
      return `| [\`${r.id}\`](https://github.com/koala73/worldmonitor/security/advisories/${r.id}) | ${r.severity} | ${r.platform} | ${r.external_anchor}${r.external_anchor_url ? ` ([link](${r.external_anchor_url}))` : ''} | ${findingRef} |`;
    }),
    '',
    '## Full register (all published + draft advisories)',
    '',
    '| Advisory | Severity | Class | Seam | Platform | CWE |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map((r) => `| [\`${r.id}\`](https://github.com/koala73/worldmonitor/security/advisories/${r.id}) | ${r.severity} | ${r.class} | \`${r.seam}\` | ${r.platform} | ${(r.cwe || []).join(', ')} |`),
    '',
    '## External researcher credits (do not confuse with the above)',
    '',
    ...register.external_researcher_credits.map((c) => `- **${c.researcher}** (${c.year}): ${c.findings.join('; ')} — source: ${c.source}`),
    '',
  ].join('\n');

  writeFileSync(join(ROOT, 'docs/proof-spine.md'), md);
  console.log(`generate-proof-spine: wrote docs/proof-spine.md (${rows.length} advisories, ${demoRows.length} demo-priority)`);
}

main();
